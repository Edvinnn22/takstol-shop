// ─── AUTO-RENDER ICONS ─────────────────────────────────────────
// Anywhere: <div class="step__icon" data-icon="truck"></div>
// fills itself in automatically once the DOM is ready.
function renderIcons() {
  document.querySelectorAll('[data-icon]').forEach((el) => {
    const key = el.dataset.icon;
    if (svgs.icons[key]) {
      el.innerHTML = svgs.icons[key];
    } else {
      console.warn(`svgs.icons: no icon found for "${key}"`);
    }
  });
}

document.addEventListener('DOMContentLoaded', renderIcons);